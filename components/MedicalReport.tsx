
import React, { useEffect, useState } from 'react';
import ReactMarkdown from 'react-markdown';
import { LogEntry } from '../types';
import { generateMedicalBrief, hasApiKey } from '../services/geminiService';

interface MedicalReportProps {
  logs: LogEntry[];
  onClose: () => void;
  onOpenApiKeyModal?: () => void;
}

const MedicalReport: React.FC<MedicalReportProps> = ({ logs, onClose, onOpenApiKeyModal }) => {
  const [report, setReport] = useState<string>("");
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const fetchReport = async () => {
      if (!hasApiKey()) {
        setReport("### ⚠️ Gemini API Key Required\n\nA valid Google Gemini API key is needed to analyze clinical logs and compile this physician summary.\n\nPlease click below to input your API key.");
        setLoading(false);
        return;
      }
      try {
        const text = await generateMedicalBrief(logs);
        setReport(text);
      } catch (error) {
        setReport("Failed to generate report. Please verify your Gemini API key and try again.");
      } finally {
        setLoading(false);
      }
    };
    fetchReport();
     // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  return (
    <div className="fixed inset-0 z-50 bg-slate-50 flex flex-col animate-fade-in font-sans">
      <div className="px-6 py-5 bg-white shadow-sm border-b border-slate-200 flex justify-between items-center z-10">
        <button onClick={onClose} className="text-slate-500 font-bold text-sm">Close</button>
        <h2 className="font-bold text-sm uppercase tracking-widest text-slate-900">Health Report</h2>
        <button onClick={() => window.print()} className="text-primary font-bold text-sm">Print</button>
      </div>

      <div className="flex-1 overflow-y-auto p-6 relative">
        <div className="absolute inset-0 bg-noise opacity-50 pointer-events-none"></div>
        
        {loading ? (
          <div className="flex flex-col items-center justify-center h-full space-y-6">
            <div className="relative w-16 h-16">
               <div className="absolute inset-0 border-4 border-slate-200 rounded-full"></div>
               <div className="absolute inset-0 border-4 border-primary border-t-transparent rounded-full animate-spin"></div>
            </div>
            <p className="text-slate-400 font-bold uppercase tracking-widest text-xs animate-pulse">Creating Report...</p>
          </div>
        ) : (
          <div className="prose prose-sm max-w-none bg-white p-10 rounded-[2px] shadow-lg border border-slate-200 relative mx-auto">
            <div className="absolute top-0 left-0 w-full h-2 bg-gradient-to-r from-primary to-accent"></div>
            <div className="mb-8 text-center border-b border-slate-100 pb-6">
               <h1 className="text-2xl font-bold text-slate-900 mb-1">Hyprova Research</h1>
               <p className="text-xs text-slate-400 uppercase tracking-widest">AI Health Companion</p>
            </div>
            <div className="text-slate-800 font-serif leading-relaxed">
              <ReactMarkdown components={{
                  strong: ({node, ...props}) => <strong className="font-bold text-slate-900" {...props} />,
                  h1: ({node, ...props}) => <h2 className="text-xl font-bold uppercase tracking-wide text-slate-900 mt-6 mb-3 border-b border-slate-100 pb-1" {...props} />,
                  h2: ({node, ...props}) => <h3 className="text-lg font-bold text-slate-800 mt-5 mb-2" {...props} />,
                  ul: ({node, ...props}) => <ul className="list-disc pl-5 space-y-1 my-4" {...props} />,
                  li: ({node, ...props}) => <li className="text-slate-700" {...props} />
              }}>
                {report}
              </ReactMarkdown>

              {!hasApiKey() && onOpenApiKeyModal && (
                <div className="mt-6 flex justify-center">
                  <button
                    id="medical-report-open-key-modal"
                    onClick={onOpenApiKeyModal}
                    className="px-6 py-3 bg-indigo-600 hover:bg-indigo-700 text-white font-bold text-xs rounded-xl shadow-lg shadow-indigo-500/25 transition-all active:scale-95"
                  >
                    Enter Gemini API Key
                  </button>
                </div>
              )}
            </div>
            <div className="mt-12 pt-6 border-t border-slate-100 flex justify-between items-center text-[10px] text-slate-400 uppercase tracking-wider">
              <span>Generated by AI Algorithm v2.5</span>
              <span>{new Date().toLocaleDateString()}</span>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};

export default MedicalReport;
